/**
 * Query types that can produce administrative/tax-dispute answers and therefore
 * receive TAX_DISPUTE_SECTION.
 */
const TAX_DISPUTE_QUERY_TYPES: Set<QueryType> = new Set([
  'legal_consultation',
  'practice_analysis',
  'comparative_analysis',
  'institutional_analysis',
  'calculation',
]);

/**
 * Get the prompt sections applicable for a given queryType.
 */
export function getPromptSectionsForQueryType(queryType?: QueryType): string {
  if (!queryType) return '';

  const parts: string[] = [];

  // Add queryType-specific section
  const section = QUERY_TYPE_PROMPT_SECTIONS[queryType];
  if (section) {
    parts.push(section);
  }

  // Court-related query types also get precedent_status rules
  if (COURT_QUERY_TYPES.has(queryType) && queryType !== 'case_lookup') {
    const courtSection = QUERY_TYPE_PROMPT_SECTIONS.case_lookup;
    if (courtSection) {
      parts.push(courtSection);
    }
  }

  // CORE-97: tax-dispute answers must state the burden-of-proof rule (ст. 77 КАС)
  if (TAX_DISPUTE_QUERY_TYPES.has(queryType)) {
    parts.push(TAX_DISPUTE_SECTION);
  }

  return parts.join('\n\n');
}
